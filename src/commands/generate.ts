import { readFileSync } from "node:fs";
import { join } from "node:path";
import { nonDurableControlErrorClassifications } from "../control/errors.js";
import { controlErrorCatalog } from "../panel/controlErrors.js";
import { usageLine } from "./help.js";
import { commandPath, GLOBAL_FLAGS } from "./parse.js";
import { ESCAPE_HATCH_ONLY, REGISTRY } from "./registry.js";
import type { CommandDef } from "./types.js";

/**
 * CLI v2 spec §10, §11 (plan Task 13): what `npm run gen:cli-docs` writes, computed from the registry. Pure: the inputs
 * are the registry, the package version, the error catalog and the current hand-written texts it splices into
 * (SKILL.md's frontmatter `version:`, docs/cli.md between its markers). tests/commands/drift.test.ts compares the result
 * with the committed files byte for byte.
 */
export const GENERATED_HEADER = "<!-- generated by `npm run gen:cli-docs` from src/commands/registry.ts; edit the registry, not this file -->";
export const CLI_DOC_BEGIN = "<!-- generated:commands -->";
export const CLI_DOC_END = "<!-- /generated:commands -->";

const SKILL = "skills/orca-control/SKILL.md";
const REFERENCES = "skills/orca-control/references";
const CLI_DOC = "docs/cli.md";
/** Not in the skill's references: `dev` is for developing Orca itself (MCP refuses it); `control` is escape-hatch.md, by hand. */
const NOT_REFERENCED = new Set(["dev", "control"]);
/** The commands that are a whole domain (`orca status`) share one reference. */
const BASICS = "basics";

export interface GeneratorInputs {
  registry: readonly CommandDef[];
  version: string;
  errors: { catalog: ReadonlyArray<{ code: string; status: number }>; internal: Readonly<Record<string, string>> };
  skill: string;
  cliDoc: string;
}

export function generatorInputs(root: string): GeneratorInputs {
  return {
    registry: REGISTRY,
    version: (JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as { version: string }).version,
    errors: { catalog: controlErrorCatalog(), internal: nonDurableControlErrorClassifications },
    skill: readFileSync(join(root, SKILL), "utf8"),
    cliDoc: readFileSync(join(root, CLI_DOC), "utf8"),
  };
}

const who = (def: CommandDef): string =>
  def.access === "token" ? "a person: needs a person token over the socket (`orca login`, then `--as-person`)"
    : def.access === "panel-local" ? "anyone; runs here, needs no panel"
    : "open over the socket (a flag marked human-only still needs a person token)";

const does = (def: CommandDef): string =>
  def.mapsTo.kind === "verb" ? `sends control verb \`${def.mapsTo.verb}\`${def.mapsTo.requiresIfRevision ? "; refused here without `--if-revision`" : ""}`
    : def.mapsTo.kind === "read" ? "reads from the panel (no write)"
    : "runs locally";

function commandSection(def: CommandDef): string {
  const lines = [`## \`${usageLine(def)}\``, "", def.summary, "", `- What it does: ${does(def)}.`, `- Who may: ${who(def)}.`];
  for (const p of def.positionals) lines.push(`- \`<${p.name}>\`${p.required ? "" : " (optional)"}${p.variadic ? " (one or more)" : ""}: ${p.summary}`);
  for (const f of def.flags) {
    const value = f.type === "boolean" ? `--${f.name}` : `--${f.name} <${f.type === "integer" ? "n" : f.name}>`;
    lines.push(`- \`${value}\`${f.required ? " (required)" : ""}${f.repeatable ? " (repeatable)" : ""}: ${f.summary}${f.humanOnly ? " — human-only: needs a person token" : ""}`);
  }
  if (def.exitCodes !== undefined) lines.push(`- Exit codes: ${Object.entries(def.exitCodes).map(([code, meaning]) => `${code} ${meaning}`).join("; ")}.`);
  if (def.examples.length > 0) lines.push("", "```", ...def.examples, "```");
  return lines.join("\n");
}

function referenceFile(title: string, intro: string, rows: readonly CommandDef[]): string {
  return [GENERATED_HEADER, "", `# ${title}`, "", intro, "", rows.map(commandSection).join("\n\n"), ""].join("\n");
}

function errorCodes(errors: GeneratorInputs["errors"]): string {
  const rows = [...errors.catalog].sort((a, b) => (a.code < b.code ? -1 : a.code > b.code ? 1 : 0));
  const internal = Object.entries(errors.internal).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return [
    GENERATED_HEADER, "", "# Error codes", "",
    "Every refusal the panel answers by name, with its HTTP status. Under `--json` it is `body.error.code`; exit 2.",
    "A `retryable: true` error may be sent again with the same command id; anything else needs a change first (re-read, ask a person, fix the input).",
    "", "| code | status |", "|---|---|",
    ...rows.map((row) => `| \`${row.code}\` | ${row.status} |`),
    "", "## Never answered by name", "",
    "These are the control plane's own failures. The panel answers them as `control-internal-error` (500, retryable): read `orca status`, then retry.",
    "", internal.map(([code, kind]) => `\`${code}\` (${kind})`).join(", "), "",
  ].join("\n");
}

function outputAndExitCodes(registry: readonly CommandDef[]): string {
  const own = registry.filter((def) => def.exitCodes !== undefined && !(def.mapsTo.kind === "verb" || def.mapsTo.kind === "read"));
  return [
    GENERATED_HEADER, "", "# Output and exit codes", "",
    "Default output is human text. `--json` prints exactly one line:", "",
    "```", `{"schema":"orca-cli-response-v1","status":<http status, 0 when refused here>,"commandId":"<id, a write>","body":<answer>,"request":<only when the outcome is uncertain>}`, "```", "",
    "When `request` is present the outcome is uncertain (timeout, dropped connection, `retryable: true`): `orca command retry --request <file|->` looks the id up and resends exactly those bytes. Never re-run the command with a new id.",
    "", "| exit | meaning |", "|---|---|",
    "| 0 | the panel answered 2xx (or a local command succeeded) |",
    "| 1 | refused here, before anything was sent |",
    "| 2 | the panel answered an error; `body.error.code` names it (see error-codes.md) |",
    "| 3 | the CLI crashed |",
    "", "## Commands with their own exit codes", "",
    ...own.map((def) => `- \`orca ${commandPath(def)}\`: ${Object.entries(def.exitCodes!).map(([code, meaning]) => `${code} ${meaning}`).join("; ")}`),
    "", "## Global flags", "",
    ...GLOBAL_FLAGS.map((flag) => `- \`--${flag.name}${flag.type === "boolean" ? "" : ` <${flag.type === "integer" ? "n" : flag.name}>`}\`: ${flag.summary}`),
    "",
  ].join("\n");
}

function cliDocSection(registry: readonly CommandDef[], cliDoc: string): string {
  const begin = cliDoc.indexOf(CLI_DOC_BEGIN);
  const end = cliDoc.indexOf(CLI_DOC_END);
  if (begin === -1 || end === -1 || end < begin) throw new Error(`${CLI_DOC} has no ${CLI_DOC_BEGIN} … ${CLI_DOC_END} markers`);
  const body = [
    CLI_DOC_BEGIN, GENERATED_HEADER, "",
    "## Commands", "",
    "`orca <domain> <action> [ids] [--flags]`; `orca help <domain> [<action>]` prints the same from the registry. Agents: the orca-control skill's references.", "",
    ...[...new Set(registry.map((def) => def.domain))].flatMap((domain) => [
      `### \`orca ${domain}\``, "",
      ...registry.filter((def) => def.domain === domain).map((def) => `- \`${usageLine(def)}\` — ${def.summary}${def.access === "token" ? " (person token)" : ""}`),
      "",
    ]),
    `Escape-hatch only (no command; \`orca control send\`): ${ESCAPE_HATCH_ONLY.map((verb) => `\`${verb}\``).join(", ")}.`,
    "", CLI_DOC_END,
  ].join("\n");
  return `${cliDoc.slice(0, begin)}${body}${cliDoc.slice(end + CLI_DOC_END.length)}`;
}

/** Spec §8: the skill's frontmatter carries `version:` equal to the package's, written here (after `description:`). */
function skillWithVersion(skill: string, version: string): string {
  const match = /^---\n([\s\S]*?)\n---\n/.exec(skill);
  if (match === null) throw new Error(`${SKILL} has no frontmatter`);
  const lines = match[1]!.split("\n").filter((line) => !line.startsWith("version:"));
  const at = lines.findIndex((line) => line.startsWith("description:"));
  lines.splice(at === -1 ? lines.length : at + 1, 0, `version: ${version}`);
  return `---\n${lines.join("\n")}\n---\n${skill.slice(match[0].length)}`;
}

/** Every generated file, keyed by its path relative to the repository root. */
export function generateDocs(inputs: GeneratorInputs): Map<string, string> {
  const files = new Map<string, string>();
  const referenced = inputs.registry.filter((def) => !NOT_REFERENCED.has(def.domain));
  const basics = referenced.filter((def) => def.action === null);
  files.set(`${REFERENCES}/${BASICS}.md`, referenceFile("Basics: status, doctor, version, help, login, logout", "The commands that are a whole domain. `orca status` first when anything looks wrong.", basics));
  for (const domain of [...new Set(referenced.filter((def) => def.action !== null).map((def) => def.domain))]) {
    files.set(`${REFERENCES}/${domain}.md`, referenceFile(`orca ${domain}`, `Every \`orca ${domain}\` command. Ids: a full id, a unique prefix, or (projects) a name or path.`, referenced.filter((def) => def.domain === domain)));
  }
  files.set(`${REFERENCES}/error-codes.md`, errorCodes(inputs.errors));
  files.set(`${REFERENCES}/output-and-exit-codes.md`, outputAndExitCodes(inputs.registry));
  files.set(CLI_DOC, cliDocSection(inputs.registry, inputs.cliDoc));
  files.set(SKILL, skillWithVersion(inputs.skill, inputs.version));
  return files;
}
