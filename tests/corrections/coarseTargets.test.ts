// Flow engine spec §13 (W-COR, criterion C20). A person can correct "the repository, in one sentence" or "this run"
// without naming a ledger row (H30). Why each assertion matters:
// - the four target shapes are the whole widening; `pendingId` alone still names nothing and stays refused;
// - every correction id and fix-run id already on disk must stay what it is, or `--close` and the debug group would
//   look for closing rows under a different file name (the stored fixture was generated by the UNCHANGED code);
// - closing one names no ledger row, so it writes one `decision` and never an `overturned` (an agent never writes one);
// - metrics must not fold them into a decision rate, and say how many there are on their own line;
// - a `dir:` project has no git remote, so ccmem (keyed by remote) must never receive its corrections.

const fixture = JSON.parse(readFileSync(new URL("../fixtures/corrections/existing-ids.json", import.meta.url), "utf8")) as {
  generatedAt: string; rows: Array<{ row: Record<string, unknown>; id: string; fixRunId: string }>;
};

const AT = "2026-10-22T00:00:00.000Z";
const BASE = { projectKey: "github.com/biran/a", kind: "wrong", because: "the export page lost its totals", at: AT, by: "amy" } as const;
const repoOnly: CorrectionRow = { ...BASE };
const bareRun: CorrectionRow = { ...BASE, runId: "orca-t1-0123abcd" };

const issues = (row: Record<string, unknown>): string[] => {
  const parsed = correctionSchema.safeParse({ id: "c_0", ...row });
  return parsed.success ? [] : parsed.error.issues.map((issue) => issue.message);
};

describe("the four correction targets (W-COR, spec §13.1)", () => {
  it("accepts repository-only and bare-run rows next to the two existing shapes", () => {
    expect(issues(repoOnly)).toEqual([]);
    expect(issues(bareRun)).toEqual([]);
    expect(issues({ ...BASE, decisionId: "orca-t1-0123abcd/1" })).toEqual([]);
    expect(issues({ ...BASE, runId: "r", pendingId: "pending-r-0" })).toEqual([]);
  });

  it("refuses pendingId without runId, and a decision together with a run", () => {
    const [refusal] = issues({ ...BASE, pendingId: "pending-r-0" });
    expect(refusal).toMatch(/pendingId/);
    expect(issues({ ...BASE, decisionId: "r/1", runId: "r" })).toHaveLength(1);
    expect(issues({ ...BASE, decisionId: "r/1", runId: "r", pendingId: "pending-r-0" })).toHaveLength(1);
    expect(issues({ ...BASE, decisionId: "r/1", pendingId: "pending-r-0" })).toHaveLength(1);
  });

  it("reads each shape through the one target reader", () => {
    expect(correctionTargetOf(repoOnly)).toEqual({ kind: "repository" });
    expect(correctionTargetOf(bareRun)).toEqual({ kind: "run", runId: "orca-t1-0123abcd" });
    expect(() => correctionTargetOf({ ...BASE, pendingId: "pending-r-0" } as CorrectionRow))
      .toThrowError(expect.objectContaining({ code: CORRECTION_ROW_INVALID }));
  });
});

describe("existing correction ids are unchanged (stored fixture, generated before W-COR)", () => {
  it("re-derives every stored id and fix-run id byte-for-byte", () => {
    expect(fixture.generatedAt).toBe("c688d1ca");
    expect(fixture.rows).toHaveLength(5);
    for (const stored of fixture.rows) {
      const row = stored.row as CorrectionRow;
      expect(issues(row)).toEqual([]);
      expect(deriveCorrectionId(row)).toBe(stored.id);
      expect(deriveFixRunId(row, stored.id)).toBe(stored.fixRunId);
    }
  });

  it("omits absent fields from the canonical JSON and from the stored line", async () => {
    // Absent is omitted, never null: a repository-only row carries no target key at all.
    expect(Object.keys(JSON.parse(canonicalCorrectionJson(repoOnly)))).toEqual(["projectKey", "kind", "because", "at", "by"]);
    await withCorrectionsDir(async (dir) => {
      await recordNewCorrection(dir, { ...repoOnly, decisionId: undefined, runId: undefined, pendingId: undefined }, { again: false });
      const [line] = (await readFile(correctionsFile(dir), "utf8")).trim().split("\n");
      expect(Object.keys(JSON.parse(line!))).toEqual(["id", "projectKey", "kind", "because", "at", "by"]);
    });
  });

  it("records two different sentences on one repository by one person, and refuses the same one twice", async () => {
    // With no decision, run or pending id in the duplicate key, every repository-only row of a person would look alike.
    await withCorrectionsDir(async (dir) => {
      await recordNewCorrection(dir, repoOnly, { again: false });
      await recordNewCorrection(dir, { ...repoOnly, because: "and the dates are in UTC", at: "2026-10-22T00:00:01.000Z" }, { again: false });
      await recordNewCorrection(dir, bareRun, { again: false });
      expect((await readCorrections(dir)).map((row) => row.because)).toEqual([BASE.because, "and the dates are in UTC", BASE.because]);
      await expect(recordNewCorrection(dir, { ...repoOnly, at: "2026-10-22T00:00:02.000Z" }, { again: false }))
        .rejects.toMatchObject({ code: "correction-already-recorded" });
    });
  });
});

describe("closing a coarse correction (spec §13.4)", () => {
  const correction = (row: CorrectionRow): Correction => ({ id: deriveCorrectionId(row), ...row });
  const undo = { how: "git revert --no-edit abc1234" };

  it("is one major decision row, valid in the ledger, and never an overturned", () => {
    for (const row of [repoOnly, bareRun]) {
      const derived = deriveCoarseRows({ correction: correction(row), choseInstead: "keep the totals row", undo, at: AT, runId: "orca-fix-00000000", authored: undefined, located: null });
      expect(Object.keys(derived)).toEqual(["decision"]);
      expect(decisionEventSchema.parse(derived.decision)).toEqual(derived.decision);
      expect(derived.decision).toMatchObject({ ev: "decision", id: "orca-fix-00000000/1", chose: "keep the totals row", because: BASE.because, importance: "major" });
      expect(derived.decision.evidence![0]).toBe(`correction ${correction(row).id}`);
    }
    expect(deriveCoarseRows({ correction: correction(bareRun), choseInstead: "x", undo, at: AT, runId: "f", authored: undefined, located: null }).decision.evidence)
      .toContain("run orca-t1-0123abcd");
  });

  it("cites the decision the agent located in `because`", () => {
    const located = { decisionId: "orca-t1-0123abcd/agent-0", paths: ["src/export.ts"], because: "the totals row was dropped there" };
    const { decision } = deriveCoarseRows({ correction: correction(repoOnly), choseInstead: "x", undo, at: AT, runId: "f", authored: undefined, located });
    expect(decision.because).toContain(BASE.because);
    expect(decision.because).toContain("orca-t1-0123abcd/agent-0");
    expect(decision.evidence).toContain("located orca-t1-0123abcd/agent-0");
  });
});

let cleanups: Array<() => Promise<void>> = [];
afterEach(async () => { for (const c of cleanups.reverse()) await c(); cleanups = []; });

describe("metrics report coarse corrections on their own line (spec §13.4)", () => {
  it("counts them apart from the rates and from corrections on unrecorded decisions", async () => {
    await withCorrectionsDir(async (dir) => {
      const root = await realpath(await mkdtemp(join(tmpdir(), "orca-metrics-root-")));
      cleanups.push(() => rm(root, { recursive: true, force: true }));
      const repo = join(root, "a");
      await mkdir(join(repo, ".decisions"), { recursive: true });
      await git(repo, ["init", "-q"]);
      await git(repo, ["remote", "add", "origin", "https://github.com/biran/a.git"]);
      await recordNewCorrection(dir, repoOnly, { again: false });
      await recordNewCorrection(dir, bareRun, { again: false });
      await recordNewCorrection(dir, { ...BASE, runId: "r", pendingId: "pending-r-0" }, { again: false });
      const report = computeMetrics(await collect({ root, repos: [], correctionsDir: dir, now: () => "2026-10-23T00:00:00.000Z" }));
      expect(report.correction_rate.corrections_total_including_stale).toBe(0);
      expect(report.corrections_on_unrecorded_decisions).toBe(1);
      expect(report.corrections_on_coarse_targets).toBe(2);
      expect(renderTable(report)).toContain("corrections naming only a repository or a run (in none of the rates): 2");
    });
  });
});

describe("ccmem export of coarse corrections (spec §13.1, §13.4)", () => {
  it("names the target in the memory head", () => {
    const text = (row: CorrectionRow) => correctionMemoryText({ id: "c_1", ...row }, null);
    expect(text(repoOnly)).toMatch(/^Orca correction: the person ruled the work in repository github\.com\/biran\/a wrong\./);
    expect(text(bareRun)).toMatch(/^Orca correction: the person ruled run orca-t1-0123abcd wrong\./);
    expect(text(repoOnly)).toContain("[repository github.com/biran/a; correction c_1]");
  });

  it("skips a dir: project's correction by name, and still exports a repository one", async () => {
    expect(isDirProjectKey(`${DIR_PROJECT_KEY_PREFIX}notes`)).toBe(true);
    expect(isDirProjectKey("github.com/biran/a")).toBe(false);
    const dir = await realpath(await mkdtemp(join(tmpdir(), "orca-corr-exports-")));
    const repo = await realpath(await mkdtemp(join(tmpdir(), "orca-corr-repo-")));
    cleanups.push(() => rm(dir, { recursive: true, force: true }), () => rm(repo, { recursive: true, force: true }));
    const item = (c: Correction): CorrectionListItemV1 => ({
      correction: c, repoId: "repo", debugGroups: [], closed: { state: "closed", ref: "refs/heads/main", via: "by-hand" }, closing: null, withdrawn: null,
    });
    const calls: string[] = [];
    const deps: CorrectionExporterDeps = {
      ccmemBin: "/fake/ccmem", env: {}, correctionsDir: dir, now: () => 1,
      listCorrections: async () => [item({ id: "c_dir", ...repoOnly, projectKey: `${DIR_PROJECT_KEY_PREFIX}notes` }), item({ id: "c_git", ...repoOnly })],
      repositoryPath: (repoId) => (repoId === "repo" ? repo : null),
      call: async (_bin, _env, _cwd, verb, input) => { calls.push(`${verb}:${(input as { id: string }).id}`); return { kind: "ok", body: { memoryId: 1 } }; },
    };
    const result = await exportCorrectionsPass(deps);
    expect(calls).toEqual(["upsert:c_git"]);
    expect(result.upserted).toEqual(["c_git"]);
  });
});
