import { mkdirSync,writeFileSync,openSync,fsyncSync,closeSync } from "node:fs";
import { join } from "node:path";
import { openControlStore } from "../../../src/control/store.ts";
import { seedBudgetCase } from "./store.ts";
import { claimWork } from "../../../src/control/budget.ts";
import { startClaim } from "../../../src/control/dispatch.ts";
import { hashPayload } from "../../../src/control/commands.ts";
import { ControlService } from "../../../src/control/service.ts";
import { collectControlled,makeControlledExecution } from "../../../src/control/schedulerBridge.ts";
import { archiveRun } from "../../../src/control/archive.ts";
import { commitCandidate } from "../../../src/control/checkpoints.ts";
import { publishPending } from "../../../src/control/projection.ts";
import { cleanupCommittedRun } from "../../../src/control/cleanup.ts";
import { landIntoW } from "../../../src/scheduler/land.ts";
import { roundPeer } from "./roundPeer.ts";
import { git } from "./archive.ts";
const [root,point]=process.argv.slice(2);
const mark=async(where)=>{if(where!==point)return;const file=join(root,"marker");const fd=openSync(file,"wx",0o600);writeFileSync(fd,where);fsyncSync(fd);closeSync(fd);process.stdout.write("MARKER "+where+"\n");await new Promise(()=>setInterval(()=>{},1000));};
const target=join(root,"target");mkdirSync(target,{recursive:true});git(target,"init","-q");writeFileSync(join(target,"seed"),"base\n");git(target,"add",".");git(target,"commit","-qm","base");const base=git(target,"rev-parse","HEAD").toString().trim();git(target,"checkout","-qb","orca/w");
const store=await openControlStore({stateDir:join(root,"state")});const seed=seedBudgetCase(store);const claim=claimWork(store,seed.t1Claim);
writeFileSync(join(root,"run.json"),JSON.stringify({runId:claim.runId,target,base}));
await mark("after-claim");
const peer=roundPeer(join(root,"peer")),service=new ControlService(store,peer);
const sourceDir=join(root,"runs",claim.runId);mkdirSync(join(root,"runs"),{recursive:true});
await startClaim(store,peer,{protocol:2,claim,contractHash:hashPayload(seed.w1.contract),inputCheckpoint:null,work:{contract:seed.w1.contract,targetRepo:target,base,sourceDir}});
await mark("after-accept");
const report=await collectControlled(service,claim.runId),terminal=report.terminal;
const run={runId:claim.runId,workdir:sourceDir,outcome:terminal.outcome,attemptSha:terminal.attemptSha};
const plan={targetRepo:target,workBranch:"orca/w",runsDir:join(root,"runs")};
await makeControlledExecution(service,"g1").land(plan,[run],run.attemptSha,()=>landIntoW(plan,run));
const archive=await archiveRun(store,{runId:claim.runId,sourceDir,repoDir:join(sourceDir,"repo"),stopProof:report.candidate.stopProof});
await mark("after-archive");
const {groupId,workItemId,taskId,runId,generation,graphVersion,targetVersion}=claim;
const candidate={groupId,workItemId,taskId,runId,generation,graphVersion,targetVersion,checkpointId:"settle-"+runId,usageHighWater:2,result:"complete",artifacts:[...archive.artifacts,...report.candidate.artifacts,report.candidate.handoff],snapshot:archive.snapshot,missing:[],unresolvedRequestIds:[],stopProof:report.candidate.stopProof,terminalOutcome:"succeeded",handoff:report.candidate.handoff};
await commitCandidate(store,candidate,{afterTransaction:()=>mark("after-transaction")});
await mark("before-projection");await publishPending(store);
await cleanupCommittedRun(store,runId,sourceDir,{beforeCleanup:()=>mark("before-cleanup")});
throw new Error("missed-crash-point "+point);
