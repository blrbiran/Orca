// CLI v2 spec §4, §12.4 (plan Task 14): the old top-level names are removed without aliases (human ruling). Each answers
// with its v2 command and exit 1, and no file an agent or a person reads still tells them to type one.
import { spawnSync } from "node:child_process";
import { mkdtempSync, openSync, closeSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";
import { main } from "../../src/cli.js";
import { captureStreams } from "../scheduler/sandbox.js";

/**
 * Removed name → the argv that used to run it → the v2 command the refusal must name. Every argv is one the OLD arm would
 * have refused or run harmlessly inside SANDBOX (measured: a red run of `agents init` with the real environment wrote
 * ~/.orca/agents.json.draft.json, CLAUDE.md Rule 17), so the mutation "re-add an arm" is safe to see red.
 */
const SANDBOX = mkdtempSync(join(tmpdir(), "removed-names-home-"));
const REMOVED: Array<[string, string[], string]> = [
  ["validate", ["validate", "x.jsonl"], "decision validate"],
  ["plan", ["plan", "plans/round.json"], "plan preview"],
  ["correct", ["correct", "--decision", "r/1"], "dev correct"],
  ["metrics", ["metrics"], "decision metrics"],
  ["compact-reviews", ["compact-reviews"], "decision compact-reviews"],
  ["level", ["level", "--hook", "claude-code"], "dev level"],
  ["gate", ["gate", "--hook", "claude-code"], "dev gate"],
  ["chain", ["chain", "start", "--repo", SANDBOX], "dev chain start"],
  ["agents", ["agents", "init"], "agent init"],
  ["checkpoint", ["checkpoint", "write"], "dev checkpoint write"],
  ["resume", ["resume", "--repo", SANDBOX], "dev resume"],
  ["check-append-only", ["check-append-only"], "dev check-append-only"],
];
const NAMES = REMOVED.map(([name]) => name);

/** Spec §12.4's scan set. */
const SCANNED = ["src", "scripts", "skills", "docs/cli.md", "README.md", ".claude", "package.json", "tests"];
const THIS_FILE = "tests/commands/removedNames.test.ts";
const GENERATED_HEADER = "<!-- generated by `npm run gen:cli-docs`";

/**
 * The allow-list: occurrences that are not an instruction to type a removed command. Each entry names its file, the text
 * it allows and why. Everything else the scan finds is a failure.
 */
const ALLOWED: Array<{ file: string; text: string; why: string }> = [
  // A chain's macOS notification title and body are labels, not commands (run.ts, notify.ts), pinned by the chain criteria.
  { file: "src/chain/run.ts", text: "orca chain ${stop.category}", why: "notification title" },
  { file: "src/chain/notify.ts", text: "orca chain ${r.chainId}", why: "notification text" },
  { file: "tests/chain/run.test.ts", text: "orca chain done", why: "notification title" },
  { file: "tests/chain/run.test.ts", text: "orca chain ${ID} stopped", why: "notification text" },
  { file: "tests/chain/cli.test.ts", text: "orca chain chain-0000000e stopped", why: "notification text" },
  { file: "tests/chain/cli.test.ts", text: "\"orca chain done\"", why: "notification title" },
  // The prompt an unattended session reads names what it is part of, not a command.
  { file: "src/chain/prompt.ts", text: "an unattended orca chain (", why: "prose noun in the session prompt" },
  { file: "tests/chain/prompt.test.ts", text: "an unattended orca chain (", why: "prose noun in the session prompt" },
  // Historical records quoted verbatim (an erratum quotes the sentence it corrects; a measurement names what was run).
  { file: "src/panel/api.ts", text: "exclusively `orca correct --close`", why: "the sentence an erratum below it quotes, and the quote" },
  { file: "src/corrections/record.ts", text: "Measured on the real CLI: `orca correct --kind", why: "a 2026-09-10 measurement of the old command" },
];

interface Hit { file: string; line: number; text: string; name: string; after: string }

const OCCURRENCE = new RegExp(`(?<![\\w./-])(?:orca|cli\\.ts) (${NAMES.map((n) => n.replace(/-/g, "\\-")).join("|")})(?![\\w-])`, "g");

function generatedLines(file: string): Set<number> | "all" {
  const lines = readFileSync(file, "utf8").split("\n");
  if (lines[0]!.startsWith(GENERATED_HEADER)) return "all";
  const inside = new Set<number>();
  let on = false;
  lines.forEach((line, i) => {
    if (line.startsWith("<!-- generated:commands -->")) on = true;
    if (line.startsWith("<!-- /generated:commands -->")) on = false;
    if (on) inside.add(i + 1);
  });
  return inside;
}

/** Spawned grep, its output to a temp file read back whole (CLAUDE.md Rule 14), then each occurrence classified. */
function scan(): { offenders: string[]; allowedUsed: Set<number> } {
  const dir = mkdtempSync(join(tmpdir(), "removed-names-"));
  try {
    const out = join(dir, "grep.txt");
    const fd = openSync(out, "w");
    const result = spawnSync("grep", ["-rnE", `(orca|cli\\.ts) (${NAMES.join("|")})`, ...SCANNED], { stdio: ["ignore", fd, "inherit"] });
    closeSync(fd);
    // 0 = matches, 1 = none; anything else (a missing path) is a broken scan, not a clean one.
    expect([0, 1]).toContain(result.status);
    const offenders: string[] = [];
    const allowedUsed = new Set<number>();
    for (const row of readFileSync(out, "utf8").split("\n").filter((r) => r !== "")) {
      const [, file, line, text] = /^([^:]+):(\d+):(.*)$/.exec(row)!;
      if (file === THIS_FILE) continue;
      for (const match of text!.matchAll(OCCURRENCE)) {
        const hit: Hit = { file: file!, line: Number(line), text: text!, name: match[1]!, after: text!.slice(match.index! + match[0].length) };
        if (hit.name === "plan" && hit.after.startsWith(" preview")) continue; // the v2 command
        if (hit.after.startsWith(":")) continue; // a message label (`orca gate: …`), pinned by the hook string's sha256 and golden files
        const generated = file!.endsWith(".md") ? generatedLines(file!) : new Set<number>();
        if (generated === "all" || generated.has(hit.line)) continue; // generated from the registry: v2 by construction
        const allowed = ALLOWED.findIndex((entry) => entry.file === hit.file && hit.text.includes(entry.text));
        if (allowed !== -1) { allowedUsed.add(allowed); continue; }
        offenders.push(`${hit.file}:${hit.line}: ${hit.text.trim().slice(0, 160)}`);
      }
    }
    return { offenders, allowedUsed };
  } finally { rmSync(dir, { recursive: true, force: true }); }
}

describe("old top-level command names are gone (spec §4, §12.4)", { timeout: 60_000 }, () => {
  beforeAll(() => {
    for (const key of ["HOME", "XDG_CONFIG_HOME", "ORCA_CONTROL_DIR", "ORCA_CORRECTIONS_DIR", "ORCA_PERSON_DIR"]) vi.stubEnv(key, join(SANDBOX, key.toLowerCase()));
    vi.stubEnv("ORCA_AGENTS_TABLE", join(SANDBOX, "agents.json"));
  });
  afterAll(() => { vi.unstubAllEnvs(); rmSync(SANDBOX, { recursive: true, force: true }); });

  it.each(REMOVED)("orca %s is refused with its v2 command and exit 1, and runs nothing", async (_name, argv, v2) => {
    // stdin is given (empty) so an old hook arm could not wait on the terminal.
    const { result, stdout, stderr } = await captureStreams(() => main(argv, ""));
    expect([result, stdout, stderr]).toEqual([1, "", expect.stringContaining(`did you mean orca ${v2}?`)]);
  });

  it("no scanned file names a removed command outside the allow-list, and every allow-list entry is still needed", () => {
    const { offenders, allowedUsed } = scan();
    expect(offenders).toEqual([]);
    expect(ALLOWED.filter((_, i) => !allowedUsed.has(i)).map((entry) => `${entry.file}: ${entry.text}`)).toEqual([]);
  });
});
